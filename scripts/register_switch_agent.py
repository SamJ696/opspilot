"""Register the external OpsPilot agent with Switch."""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import urllib.error
import urllib.request

from config import settings
from dotenv import load_dotenv

load_dotenv(ROOT / ".env")

INTEGRATION_PROFILE = {
    "connection_model": "session_passive",
    "message_exchange": True,
    "pre_invocation_mediation": [],
    "post_invocation_mediation": [],
    "event_reporting": [],
}


def _post(url: str, payload: dict, headers: dict[str, str]) -> dict:
    request = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={**headers, "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace")
        raise SystemExit(f"Registration failed HTTP {exc.code}: {body}") from exc


def _read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def _write_env_updates(path: Path, updates: dict[str, str]) -> None:
    existing_lines: list[str] = []
    if path.exists():
        existing_lines = path.read_text(encoding="utf-8").splitlines()

    remaining = dict(updates)
    output: list[str] = []
    seen_keys: set[str] = set()
    for line in existing_lines:
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key = stripped.split("=", 1)[0].strip()
            if key in remaining:
                output.append(f"{key}={remaining.pop(key)}")
                seen_keys.add(key)
                continue
        output.append(line)

    for key, value in remaining.items():
        if key not in seen_keys:
            output.append(f"{key}={value}")

    path.write_text("\n".join(output).rstrip() + "\n", encoding="utf-8")


def _save_secret_file(path: Path, agent_id: str, api_key: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "\n".join(
            [
                "# Generated by scripts/register_switch_agent.py",
                f"SWITCH_AGENT_ID={agent_id}",
                f"SWITCH_API_KEY={api_key}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def main() -> None:
    name = os.getenv("SWITCH_AGENT_NAME", "opspilot")
    description = os.getenv(
        "SWITCH_AGENT_DESCRIPTION",
        "OpsPilot AI Engineering Operations Team for incident investigation and simulated recovery.",
    )
    overwrite = os.getenv("SWITCH_REGISTER_OVERWRITE", "").lower() in {"1", "true", "yes"}
    mode = os.getenv("SWITCH_REGISTER_MODE", "bridge").lower()
    write_env = os.getenv("SWITCH_REGISTER_WRITE_ENV", "").lower() in {"1", "true", "yes"}
    force_env = os.getenv("SWITCH_REGISTER_FORCE", "").lower() in {"1", "true", "yes"}

    if mode == "gateway":
        token = os.getenv("SWITCH_GATEWAY_SESSION", "").strip()
        result = _post(
            f"{settings.switch_gateway_url()}/gateway/agents/register-other",
            {"name": name, "description": description, "overwrite": overwrite},
            {"Cookie": token},
        )
    else:
        token = os.getenv("SWITCH_REGISTRATION_TOKEN", "").strip()
        result = _post(
            f"{settings.switch_agent_bridge_url()}/agents",
            {
                "name": name,
                "description": description,
                "connector_type": "external",
                "integration_profile": INTEGRATION_PROFILE,
                "overwrite": overwrite,
            },
            {"Authorization": f"Bearer {token}"},
        )

    agent_id = result.get("id")
    api_key = result.get("api_key")
    if not agent_id or not api_key:
        raise SystemExit(f"Unexpected registration response keys: {list(result)}")

    secret_path = ROOT / "data" / "runtime" / "switch_registration.env"
    _save_secret_file(secret_path, agent_id, api_key)

    print("OpsPilot agent registered.")
    print(f"Agent id: {agent_id}")
    print(f"Credentials saved to: {secret_path}")
    print("The API key was not printed to the terminal.")

    env_path = ROOT / ".env"
    current = _read_env(env_path)
    blocked = []
    for key in ("SWITCH_AGENT_ID", "SWITCH_API_KEY"):
        if current.get(key) and not force_env:
            blocked.append(key)
    if blocked and write_env:
        print(
            "Skipped updating .env for existing keys: "
            + ", ".join(blocked)
            + ". Set SWITCH_REGISTER_FORCE=1 to overwrite."
        )
        write_env = False

    if write_env:
        _write_env_updates(
            env_path,
            {"SWITCH_AGENT_ID": agent_id, "SWITCH_API_KEY": api_key},
        )
        print(f"Updated {env_path} with SWITCH_AGENT_ID and SWITCH_API_KEY.")
    else:
        print(
            "To merge credentials into .env automatically, run with SWITCH_REGISTER_WRITE_ENV=1."
        )

    print("Add the agent to your Mattermost room in Switch Console, then set SWITCH_ROOM_ID.")


if __name__ == "__main__":
    main()
